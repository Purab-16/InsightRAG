import re

from app.models import Insights, Message

_BULLET_FIELDS = [
    ("Datasets", "datasets"),
    ("Metrics", "metrics"),
    ("Key results", "key_results"),
    ("Limitations", "limitations"),
    ("Contributions", "contributions"),
]


def slugify(text: str, fallback: str = "export") -> str:
    """Safe ASCII file name stem: lowercase, a-z0-9 and dashes, max 60 chars."""
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60].strip("-")
    return slug or fallback


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {i}" for i in items) if items else "_None listed._"


def paper_to_markdown(paper: dict) -> str:
    """Title, metadata, abstract and every insight field of one paper."""
    lines = [f"# {paper['title']}", ""]

    if paper.get("authors"):
        lines.append(f"**Authors:** {', '.join(paper['authors'])}")
    if paper.get("published"):
        lines.append(f"**Published:** {paper['published']}")
    if paper.get("arxiv_id"):
        lines.append(f"**arXiv:** https://arxiv.org/abs/{paper['arxiv_id']}")
    lines.append("")

    if paper.get("abstract"):
        lines += ["## Abstract", "", paper["abstract"], ""]

    if not paper.get("insights"):
        lines += ["_Insights are not available for this paper._", ""]
        return "\n".join(lines)

    ins = Insights.model_validate(paper["insights"])
    lines += [
        f"**Field:** {ins.field}",
        "",
        "## TL;DR",
        "",
        ins.tldr,
        "",
        "## Problem",
        "",
        ins.problem,
        "",
        "## Method",
        "",
        ins.method,
        "",
    ]
    for heading, attr in _BULLET_FIELDS:
        lines += [f"## {heading}", "", _bullets(getattr(ins, attr)), ""]

    lines += ["---", "_Generated by InsightRAG from the paper text. Check important details in the paper._", ""]
    return "\n".join(lines)


def _source_line(s: dict) -> str:
    where = [p for p in (s.get("section"), f"p. {s['page']}" if s.get("page") else None) if p]
    tail = f" ({', '.join(where)})" if where else ""
    return f"[{s['n']}] {s['paper_title']}{tail}"


def session_to_markdown(session: dict, papers: list[dict], messages: list[Message]) -> str:
    """Paper list, then each question and answer with its numbered sources."""
    lines = [f"# {session.get('title') or 'Chat'}", "", "## Papers", ""]
    lines += [f"- {p['title']}" for p in papers]
    lines.append("")

    for m in messages:
        if m.role == "user":
            lines += [f"## Q: {m.content.strip()}", ""]
            continue
        lines += [m.content.strip(), ""]
        if m.sources:
            lines += ["**Sources**", ""]
            lines += [f"- {_source_line(s.model_dump())}" for s in m.sources]
            lines.append("")

    lines += ["---", "_Generated by InsightRAG. Answers come from the paper text; check them against the papers._", ""]
    return "\n".join(lines)
